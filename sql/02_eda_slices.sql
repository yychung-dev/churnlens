-- [B3-0] 前置驗證：B3 兩個判讀前提的實測
-- (1) 驗證 total_trans_ct 無「單值大量聚集」：支持 (五) 附註「箱界拆分影響可忽略」的前提
-- (2) 驗證 credit_limit 的額度上限 (34,516)聚集量：支持信用額度切片「第 5 箱判讀注意」的量級
-- 判讀：最大聚集值的人數相對箱容量(約 2,025)佔比低，就沒問題。
-- ============================================================
-- 依照數值分組，依照人數由大排到小。輸出「聚集人數最多的 5 個數值 + 該值對應的人數」。
-- 驗證一
-- GROUP BY 1 (第一個 SELECT 欄位 total_trans_ct)，ORDER BY 2(第二個 SELECT 欄位 COUNT(*))
-- 輸出樣貌 ：
--   val |  n
--  -----+------
--    81 |  208           ← 最多人相同的交易筆數，預期一兩百人級
--    71 |  203
--    75 |  203
--    69 |  202
--    82 |  202

SELECT total_trans_ct AS val, COUNT(*) AS n
FROM clean.customers GROUP BY 1 ORDER BY 2 DESC LIMIT 5;

-- ============================================================

-- 驗證二
-- GROUP BY 1 (第一個 SELECT 欄位 credit_limit)，ORDER BY 2(第二個 SELECT 欄位 COUNT(*))
-- 輸出樣貌：
--     val   |  n
--  ---------+------
--    34516  |  508      ← 預期第一名就是：額度上限值(產品的最高門檻額度)，約 500人 上下
--    1438.3 |  507      ← 可能的第二名：最低額度值(產品的最低門檻額度，也會聚集)
--    9959   |  18
--    15987  |  18
--    23981  |  12

SELECT credit_limit AS val, COUNT(*) AS n
FROM clean.customers GROUP BY 1 ORDER BY 2 DESC LIMIT 5;
