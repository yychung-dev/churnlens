-- ============================================================
-- [C3-a] 各旗標的規模(旗標圈到的人數)與兩兩交集 (4個正式旗標兩兩配對算交集,算「每一組名單的同時在籍人數」,eg.low_x_zero=1165就是「既在低活躍名單、又在零動用名單的人總共有 1165人」) (4 個正式旗標兩兩配對 6 組 + 下滑旗標與 4 旗標各 1 組共 4 組) 。單獨用 4 個旗標會各自圈出名單人數,但彼此會有重複的人。所以 C3-a 就是計算「實際上有幾個不重複的人」、「哪兩份名單重複最嚴重」。

-- 視角與 C2 不同: C2 之前看「誰的流失率高」(風險視角)。本C3段不看流失率,而是看「名單與名單之間,有多少人是重複的」(集合視角:交集人數、聯集人數)。C3 的觀察提供「 M5 名單去重與預算編列」參考。
-- 原因:「4 份高風險名單」的實際重疊規模需實測(待驗證清單 #3);「下滑旗標與活躍水位類」的重疊也在此量測(待驗證清單 #5)。

-- 功能:一個 CTE 計算完三種人數:(1)各旗標名單的人數 (計算重疊比例時可作為分母);(2) 10 組兩兩交集的人數 (同時在兩份名單上的人數)(前面正式旗標的 6 組數字與 C2 各段雙真格的 n 相同,eg.C2-1 雙真格 n=1,165 就是 low_x_zero(因為兩兩交集的概念同兩個旗標皆為 True),(這 6 組與 C2 的六段是完全相同的配對, 因為都是算 4 個正式旗標的兩兩交集),後面下滑旗標的 4 組是下滑旗標與4個正式旗標的交集人數);(3)4 個正式旗標的聯集人數:「至少命中一支旗標的去重名單人數」。(4)補充說明: C3-a 的 10 個交集數字有 6 個跟 C2 的雙真格 n 相同, C3-a 增加計算「下滑旗標的 4 組交集人數(C2 沒做)+ 聯集人數(C2 沒算)+ 把 10 個數字集中一列方便之後算重疊比例(算重疊比例的分子(交集)與分母(旗標人數)集中在同一列輸出,這樣之後 notebook 拿到一列資料就能直接逐對相除算比例,不需要跨好幾個查詢結果來拼湊分子與分母做計算)」。

-- 作法:1.CTE 建立五個旗標的定義 (分別定義旗標) + 攤開每位客戶的五支旗標的 True/False (每列都是一個客戶的「旗標成績單」) ; 2.再由外層一次算完:(1)各旗標人數、(2)10 組兩兩交集的人數、(3)4 個正式旗標的聯集人數。

-- 語法補充:1. SUM(旗標::int) = 名單人數 ; SUM((a AND b)::int) = 交集人數 ; SUM((a OR b OR ...)::int) = 聯集人數。2. 無 GROUP BY,全表都用 SUM 做天然聚合, 輸出單列寬表(1×16) (可讀性較低);notebook 再將 10 個交集數字重排成一張 5x5 的對稱矩陣(列與欄都是旗標名,交叉格是交集人數,方便看任兩個旗標的交集)來呈現。

-- 判讀重點:
-- 1. 重疊比例 = 交集人數 ÷ 人數較小的旗標人數 ➡ 回答「小名單被大名單吃掉幾成」。
-- (1)若重疊比例是 100%,可知「小名單是大名單的純子集」,小名單可直接被併掉、沒有獨立存在的必要(因為只留大名單就確定會圈到小名單的所有人,不會漏掉)。eg.low_x_zero/n_zero = 1165/2470 = 47.2%,意思是「零動用名單裡有 47.2% 的人同時也在低活躍名單上」,表示「零動用名單中有過半的人並非低活躍名單,在零動用名單中有 52.8% 是低活躍名單圈不到的」, 這 52.8% 的人是零動用名單的獨立價值所在, 所以不能因為零動用名單較小就直接把它併掉,因為其中有52.8%的人有獨立價值、不可被忽略)。這樣的結果也表示「零動用 & 低活躍這兩個訊號是各自有其獨立資訊，並非高度重疊的重複資訊」。(超過多少%算高度重疊:不直接用多少%來判斷重疊程度,因為這種判斷需要多種因素綜合判斷(通常50%以上可稱重疊程度高、80-90%才到近乎子集合考慮合併,但還是必須綜合因素考量,不單以%數字判斷),此判斷會在 notebook 做判讀。)
-- (2)為什麼是除以「人數較少」的那份名單(1165/2470 = 47.2%):因為要回答「小名單裡有多少被大名單吃掉」(小名單裡有 47.2% 被大名單吃掉)。若是除以「人數較多」的那份名單(1165/4165 = 28%),回答的是「低活躍名單(大名單)裡有多少零動用(小名單)」,所以要把低活躍名單(大名單)放在分母才能回答這個問題。而若要回答「小名單要不要獨立存在」這個決策,就要把「小名單的人數」放在分母,才能得到「小名單中有多少也在大名單裡(被大名單吃掉)」再去做決策。
-- 2.「計算聯集 vs 直接加總」的差別: 四旗標各自的名單若直接加總會是 10,410 人次 (4,165+2,470+2,153+1,622 = 10,410 人次,是四份名單疊起來的表面規模),而計算聯集(去重後的真實人數)僅 7,292 人。兩者的差額 3,118 就是重複計算的人次。若聯集人數遠小於直接加總的人數,表示名單有高度重複。
-- 「跨假設觀察第 2 點」的驗證: 人「次」不等於人「數」。差額的 3118 是重複了三成人次, 證實「七個訊號並非七群不同的人,而是彼此之間有重複」, 所以 M5 編預算、發訊息觸及高風險客戶時應針對 7292 人這份去重名單, 不是按照 10410 人次去動作。 
-- 本實測的其他觀察: 7,292 佔全體 10,127 的 72%, 表示「四支旗標就圈掉了七成客戶」,這個覆蓋率本身值得判讀, 是「旗標圈得太寬」還是「這些組合資訊要配合 C3-b 的旗標命中數分層來觀察」,需要在 C3-b 的旗標命中數分層做觀察與判讀 (不只看是否被名單圈到,重點要看「旗標命中數的分層」:命中 1 支旗標和命中 4 支旗標的風險差很多)。
