-- [C1] H5 (avg_utilization_ratio) 用「二分」重新驗證:零動用率 vs 有動用率
-- 原因:五分位下零值人口溢箱(第 1/2 箱邊界模糊),精確幅度(diff_pp)需以乾淨切法重測(待驗證清單 #2)。
-- 功能:取得零動用訊號的精確 n 與 diff_pp,取代五分位版本,供候選洞察清單 v2 引用。
-- 作法:依 avg_utilization_ratio 是否為 0 做「二分」,各組(兩組)分別算流失率

-- 語法說明:
-- (1)CASE WHEN 產生組別標籤 (grp這個組別有「零動用(=0)」和「有動用(>0)」這兩種標籤)(詳細語法說明參考本檔底部筆記)
-- (2)GROUP BY 1 的意思: 「按SELECT清單裡的第1個輸出欄分組」(1 是位置編號,不是數值)。C1的第1個輸出欄就是CASE WHEN 製造出來的衍生欄位(grp欄位),所以 GROUP BY 1 = 按 grp 分組。(詳細語法說明參考本檔底部筆記)

-- [C1] 輸出樣貌(單層,2 列;零動用組在前(ORDER BY churn_pct DESC)):
--        grp     |  n    | churn_pct | diff_pp
--    零動用(=0)   | 2470  |   36.15   |  +20.08   ← 判讀重點:精確的 n 與 diff_pp,取代五分位版的 2,026(n)與 35.19(diff_pp)
--    有動用(>0)   | 7657  |    9.59   |   -6.48
-- (兩列 n 相加 = 10,127;零動用的 n 預期會略多於 2,026 (因溢入到第 2 箱的零值者被規則圈回))
-- ============================================================
SELECT CASE WHEN avg_utilization_ratio = 0 THEN '零動用(=0)' ELSE '有動用(>0)' END AS grp,
       COUNT(*) AS n,
       ROUND(100.0 * AVG(is_churned::int), 2) AS churn_pct,
       ROUND(100.0 * AVG(is_churned::int) - 16.07, 2) AS diff_pp
FROM clean.customers
GROUP BY 1
ORDER BY churn_pct DESC;
