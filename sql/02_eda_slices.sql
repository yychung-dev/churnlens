-- 第一層中間表 flags(10,127 列 × 3 欄;每人標兩個布林旗標 low_activity 和 zero_util 這兩個旗標，每個客戶的這兩個旗標的值可能是 true 或 false):
--   is_churned | low_activity | zero_util
--     true     |    true      |   true
--     false    |    false     |   false
--    ... (其他每一列客戶的 is_churned、low_activity、zero_util 值)

-- 第二層最終輸出(4 格,依 churn_pct 由高到低排,流失風險最高的格永遠在第一列,判讀時能馬上看到):
--   low_activity | zero_util |   n   | churn_pct | diff_pp
--      true      |   true    | 1165  |   65.92   |  +49.85   ← 雙真: 低活躍且零動用的客群 (判讀重點)
--      true      |   false   | 3000  |   21.20   |  +5.13    ← 單真 A: 低活躍且有動用的客群
