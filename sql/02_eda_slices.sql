-- [B3] 連續數值欄：NTILE(5) 等量分箱 
-- (一)連續數值：值可能是範圍內的任何數，可能的取值非常多(甚至無限多)。對比：B2 (離散數值) 基數低 -> 逐值看；B3 (連續數值) 基數高(可能有上百種值) -> 分箱看。

-- (二)作法：1. CTE 內先用 NTILE(5) 把全體客戶依該欄排序後，依總客戶人數平均分五組(每組約 2,025 人) (等量切分)；2. 接著，外層對每組算流失率，並以 MIN/MAX 標出每箱的實際數值範圍，讓「第 1 分位」有具體含義，eg. 業務語言是：交易筆數「10筆～43筆」的那群人(第一箱、第一分位)的流失率是 35%
-- CTE 的原理：CTE(WITH binned AS (...))= 「先用 NTILE 這個 Window Function 查一張中間表並取名，再對這張中間表做最終查詢」：把巢狀的複數個子查詢攤平成兩個步驟 (先 CTE 做出中間表，再對中間表做最終查詢)。作法：先算好「每個客戶屬於第幾箱」這張中間表 (CTE)，外層再對這張中間表分組 (外層最終 SELECT)。 CTE 比巢狀的複數個子查詢更具可讀性。常用於分析 SQL 的寫法。
-- 本處的 CTE 寫法：(1) 內層先用「窗口函數」得出中間表 (2) 外層再對中間表做最終查詢 (3) 得出最終輸出的報表結果。

-- (三)判讀重點：
-- 1.第 1 五分位 (最低的 20% 那組)與 第 5 五分位(最高的 20% 那組) 的「流失率差距」
-- 2.中間是否單調過渡 (判讀不只看頭尾兩箱的落差，還要看 1→2→3→4→5 的流失率是不是一路遞減(H1 預期負相關))
-- 3.單調過渡：1→2→3→4→5 的流失率是一路遞減 or 遞增 (以H1 預期負相關為例，若實測是一路遞減，表示「交易越少流失越高」這個關係在整個範圍內都成立，證據清楚乾淨，)；非單調過渡：中間跳動(1 高、2 低、3 又高)，關係就沒那麼單純，要另找解釋。

-- (四)NTILE(5) 等量分箱：1.定義：先依指定欄位將所有資料排序後(ORDER BY)，將所有資料按筆數均分成5組(以數量為基準平均切成指定份數)，最後回傳每列所屬的組別編號(eg. 分成五組，就是編號 1–5)。
-- NTILE 是一種 Window Function (透過 OVER() 子句進行計算)

-- (五)附註：NTILE 依筆數均分、不管值是否相同，故箱界上的同值客戶可能被拆進相鄰兩箱。對本案判讀影響可忽略：此類客戶佔比極低，且潛在誤差(零點幾 pp)遠小於本案要觀測的組間差距 (預期頭尾箱差達兩位數 pp：因為通常此種流失率差距的級別，在業務上才值得投放資源挽留)。
-- 若需嚴格排除，可改按值的百分位切分(同值必同箱)，但本案無此必要，因潛在誤差的雜訊(箱界拆分造成的 <1pp 誤差)遠小於本案要觀測的訊號(箱間流失率差 20pp)。


