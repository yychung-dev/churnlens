  SUM((f_decline AND f_low)::int)     AS decline_x_low,     -- 既在下滑中名單、又在低活躍名單的人數
  SUM((f_decline AND f_zero)::int)    AS decline_x_zero,    -- 既在下滑中名單、又在零動用名單的人數
  SUM((f_decline AND f_shallow)::int) AS decline_x_shallow, -- 既在下滑中名單、又在淺關係名單的人數
  SUM((f_decline AND f_contact)::int) AS decline_x_contact, -- 既在下滑中名單、又在高聯繫名單的人數
  -- 4. 算: 4 個正式旗標的聯集人數: 計算「四支正式旗標至少中一支」的列數 (至少命中一項旗標的去重名單人數)
  -- OR + SUM 語法: 逐列看每一列客戶的這 4 個旗標是 True 或 False, 有中一個 True 就把這個客戶撈出來,然後往下看下一列客戶的這 4 個旗標是否有 True,一路看完所有客戶。最後把撈出的客戶用 SUM 加總, 得出「至少命中一項旗標」的去重客戶名單人數。
  -- 下滑旗標刻意不進聯集,因為下滑旗標(方向類訊號)不是交叉切片的四個變數,而是階段E用來確認「下滑中」是否為獨立於「活躍水位低」的訊號,階段C只是先算人數交集來做間接推估而已,主要分析與判斷是在階段E。
  SUM((f_low OR f_zero OR f_shallow OR f_contact)::int) AS union_any_formal
FROM flags;
