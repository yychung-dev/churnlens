WITH flags AS (
    -- 1. 查出每列客戶的: 「是否流失」布林值 + 收入類別(eg.$120K +) + 「是否為低信用額度」布林值(low_limit)(若是低信用額度即為True)
    SELECT is_churned, income_category,
           (credit_limit < 2307) AS low_limit
    FROM clean.customers
)
-- 2. 根據中間表得出的「收入類別」及「是否為低信用額度」,
-- (1)把「收入類別的六種」及「是否為低信用額度的兩種」兩兩配對分組 (分出 12 組) ,然後
-- (2)排序 (先按收入類別排,同收入組內再依low_limit降冪排(布林 true > false,所以 t 列在前))(文字欄位依字典序(字串比較:$1➡$4➡$6➡$8➡L➡U)排,而非依收入高低排。SQL檔這樣排即可,不影響判讀;notebook呈現時可用 Python重排成業務序如低到高,會更好讀) (注意:文字欄位排序有這個「字典序 ≠ 業務序」的特性);最後
-- (3)將 12 組分別展開呈現該組的：收入類別、是否為低信用額度、(前兩者配對出的)該組樣本數、(前兩者配對出的)該組流失率、(前兩者配對出的)該組 diff_pp

SELECT income_category, low_limit, COUNT(*) AS n,
       ROUND(100.0 * AVG(is_churned::int), 2) AS churn_pct,
       ROUND(100.0 * AVG(is_churned::int) - 16.07, 2) AS diff_pp
FROM flags
GROUP BY income_category, low_limit
ORDER BY income_category, low_limit DESC;
