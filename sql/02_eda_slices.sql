-- ============================================================
-- [B2] 低基數整數欄：逐值 GROUP BY
-- 原因：這些欄位只有 6–7 種不同數值，每個值自成一組即可完整檢視；若使用 NTILE 以人數分組做等量分箱，會把不同值混入同箱，反而看不見逐值的變化狀況(如 H2 逐月變化的形狀細節，必須逐值分組才能看清「是每個月都在提升還是升到某個月就飽和」這種形狀細節。若把同一個月的數值分散在不同箱中，就無法觀測分析逐月的變化細節) 
-- 判讀重點：流失率是否隨值單調變化(一路遞增或一路遞減)，與「假設的預期方向 (如：正相關、負相關)」做比對。

-- 註：「低基數整數欄 (Low Cardinality Integer Column）」：此欄位的資料型態是整數，且其中「不重複的值」很少 (如：扶養人數欄位的資料只有 0、1、2、3、4、5 這六種，型態皆為整數，但全欄位只有 6 種不同的數值，數值重複率高)。高基數（High Cardinality）：「不重複的值」很多 (如：使用者編號、裝置識別編號，(幾乎)每筆資料的數值都不同)
-- ============================================================

