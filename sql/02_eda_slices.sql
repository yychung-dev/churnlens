-- 業界實務常見「規則版先行、模型之後補」的做法。eg. 1.銀行反詐欺系統:最早是用「規則版」(「單筆逾 X 萬 + 境外 + 深夜 → 攔截」這類人工規則),機器學習模型是後來加上去的;且規則層至今仍保留,作為模型失效或新型詐欺出現時的防護底線(fallback)。2. 電商的客戶挽留策略也是同樣路徑:早期用「30 天未登入即發券」的規則,後來才升級成流失預測模型。

