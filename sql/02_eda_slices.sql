-- (3)CASE WHEN 產生組別標籤 (grp這個組別有「零動用(=0)」和「有動用(>0)」這兩種標籤)。詳細語法說明:C1想分的兩組(「零動用」和「有動用」)在資料裡沒有任何一個欄位的值長這樣,是由這個SQL指令自己發明的分類,所以用「CASE WHEN」來當場製造出這個分類欄:先逐列判斷「動用率是不是 0」,是的話在這列標上字串「零動用(=0)」、否則標「有動用(>0)」,並且製造出一個新欄(取名 grp),而grp欄位下的每個值就用這兩種標籤(「零動用(=0)」和「有動用(>0)」)來標示。之後，GROUP BY 依 grp 這個新欄位分組。所以「產生組別標籤」的意思就是：用條件式直接當場製造一個原本不存在的分類欄位(grp)。C2 其實也在做同一件事,只是C2直接用布林值(true/false)當標籤並做 GROUP BY、沒像C1一樣轉成中文字串。CASE WHEN 版的輸出比較好讀,布林版的程式碼比較精簡,兩種都可行)
-- (4)GROUP BY 1 的意思: 「按SELECT清單裡的第1個輸出欄分組」(1 是位置編號,不是數值)。C1的第1個輸出欄就是CASE WHEN 製造出來的衍生欄位(grp欄位),所以 GROUP BY 1 = 按 grp 分組。詳細語法說明:不直接寫GROUP BY grp的原因:因為標準 SQL 的 GROUP BY 不一定認得 SELECT 裡取的別名(執行順序上 GROUP BY 先於 SELECT,別名那時還不存在;PostgreSQL 實務上放寬了這限制,但不是所有資料庫都放寬)。不用別名的話,正規寫法是把整段 CASE WHEN 原文重抄一遍放進 GROUP BY,但這樣冗長又可能發生修改時忘記同步改到兩處導致不一致。所以使用 GROUP BY 1 用位置來指定代替前述寫法能一勞永逸,這也是是分析 SQL 的常用簡寫。代價是可讀性略降(必須回頭數SELECT清單裡的第1欄是誰),因此慣例上只會在「用衍生欄 GROUP BY 做分組」這種場景使用 GROUP BY 1 這個用法。
