-- sql/02_eda_slices.sql — M2 階段 B:單變數切片(H1–H8 + 次要檢視清單)
-- 目的:對假設樹各假設對應的欄位計算「分組流失率」,與基準 16.07% 比較,找出流失率顯著偏高的客群。
-- 執行:docker exec -i churnlens-pg psql -U postgres -d churnlens < sql/02_eda_slices.sql
-- 輸出格式(全檔案統一):組別 | n(樣本數) | churn_pct(流失率 %) | diff_pp(與基準 16.07 的差距，單位:百分點 (非 %))
--   永遠都要輸出 n (樣本數)：原因：樣本數過少的組,流失率再高也不下結論([M1 稽核 B]、notebook (02_eda_slicing.ipynb) 判讀前提)。
-- 切片方式的三分法:
-- (1) B1 類別欄直接分組 (直接 GROUP BY)：天生有組別，不需分箱。
-- (2) B2 低基數整數欄逐值分組 (逐值 GROUP BY)：值少(只有 6、7 種值，每個值本身就是一組)，用 NTILE 以人數做等量分箱反而喪失解析度，因為用 NTILE 會把不同值混進同箱，喪失原本逐值分組能達成的「逐值精度」)。
-- (3) B3 連續數值欄 (NTILE(5) 等量分箱)：值太多無法逐值看，所以分箱看。資料右偏分布，所以用等量分箱，而非等寬分箱([稽核 D] 決策)。
-- (4) H9(months_on_book)不在本階段、本檔案做切分: 因為 months_on_book 屬「代理 cohort」，見 sql/03_cohort.sql。(代理 cohort：以「單一時點快照(橫斷面資料)」這個替代方法，模擬「世代分析 (縱向追蹤)的 客戶生命週期各階段樣貌」)



-- ============================================================
-- [B1] 類別欄:直接 GROUP BY
-- 欄位：income、gender (+次要:education、marital、card)
-- 語法:AVG(is_churned::int) 即該組流失比例(boolean 轉 0/1 後取平均,[M1-4] 的口徑落地)；
--      diff_pp 為該組與全體基準的差距,正值代表高於平均,是候選洞察的第一眼指標。
-- ============================================================

-- H7：收入類別各組的流失率 (含 Unknown 類別的流失率) ([M1-1] 保留 Unknown 欄位的決策，在此處落實並用資料驗證) (GROUP BY 語法會自動給 Unknown 一組，不需其他特殊處理，是省力的語法設計) 
SELECT income_category AS grp, COUNT(*) AS n,
       ROUND(100.0 * AVG(is_churned::int), 2) AS churn_pct,
       ROUND(100.0 * AVG(is_churned::int) - 16.07, 2) AS diff_pp
FROM clean.customers
GROUP BY income_category
ORDER BY churn_pct DESC;

-- H8：性別類別各組的流失率
SELECT gender AS grp, COUNT(*) AS n,
