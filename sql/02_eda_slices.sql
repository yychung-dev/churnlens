-- ============================================================
-- H5：平均額度動用率 (預期：非單調、非一路遞增或遞減，而是看分布圖的 U 形，預期第 1 分位(動用率趨近 0)流失率明顯偏高)
-- 依平均額度使用率的大小做排序、然後依總客戶數等量分箱成五組，觀察每一組的流失率 

-- 「平均額度動用率(avg_utilization_ratio)」定義：官方未給計算公式。合理推斷為 total_revolving_bal / credit_limit (循環欠款本金/總額度) 。舉例：刷一萬五、帳單全繳清 → 欠款 0 → 額度動用率 0;刷一萬五、只繳最低 → 欠款約一萬四 → 額度動用率約 47%。是「欠著多少」，而非「刷了多少」。額度三萬的客戶，若循環欠款本金餘額為一萬五(有一萬五未清償)，動用率即 50%；若每期全額繳清，動用率趨近 0。
-- (此定義在社群普遍實測大致吻合；本案未另行驗證。「avg」一詞的確切含義(歷史平均或快照值)無法實證)。

-- 分佈呈 U 形的原因：動用率近 0 代表卡片實質已停用，是流失的訊號；中間分位正常；最高分位也可能因財務壓力大或轉向他行，流失率略升。
-- 判讀重點：看「第 1 分位的流失率是否顯著高於基準流失率 (16.07%)」，而非看「各分位組是否單調過渡」。
-- 判讀注意：動用率近 0 的判斷是建立在「欠款本金餘額」的判斷基礎上。動用率趨近 0 可能代表「沒在刷卡，是流失訊號」或「有刷卡但每期都有繳清，不是流失訊號」，所以 第 1 分位混合了「全額繳清的優質客戶」和「卡片沒在用的流失高風險群客戶」兩種人，此 U 形的左端不純粹是「流失率高的客人」。

-- avg_utilization_ratio 是 float，ROUND 到小數點後第三位 (比率的慣例)。ROUND()兩參數版 只接受 numeric 作為參數，所以要先轉。

