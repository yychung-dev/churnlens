-- CTE 兩層表的示意樣貌: 
-- 第一層中間表 flags(10,127 列 × 6 欄;每列一個客戶,標 is_churned 的 true/false + 五支旗標的 true/false):
--   is_churned | f_low | f_zero | f_shallow | f_contact | f_decline
--     true     |   t   |   t    |    t      |    f      |    t        ← 這位客戶中了 4 支旗標
--     false    |   f   |   f    |    f      |    f      |    f        ← 這位客戶一支旗標都沒中(安全)
--     false    |   f   |   t    |    f      |    f      |    f        ← 這位客戶只中零動用這支旗標(可能是全額繳清族)
--    ...(其餘每列一位客戶)
--
-- 第二層最終輸出(1 列 × 16 欄;「全表聚合、無 GROUP BY」的語法本來就只回傳一列) 
-- 只回一列的原因:因為是「聚合函式+無GROUP BY」這個組合:沒做分組時,整張表被視為一個組,每個聚合函式回一個值,所以是只有一列+多欄(每個SUM()一欄)。聚合函式的SUM()、AVG()、COUNT()都是如此:
--   n_low | n_zero | ... | low_x_zero | ... | decline_x_contact | union_any_formal
--   4165  |  2470  | ... |    1165    | ... |        410        |       7292
-- ============================================================


WITH flags AS (
    -- 查出並攤開每列客戶的 6 個欄位的布林值: 是否流失 + 是否低活躍、是否零動用、是否淺關係、是否高聯繫、是否消費下滑 (五支旗標的定義分別建立)
    -- 目的: 攤開每位客戶各自的「旗標成績單」,讓外層可以對成績單做任何集合統計 (is_churned欄位其實沒被外層引用,可刪;保留是為了與C2、C3各段查詢的 CTE 模板(SELECT is_churned, 旗標定義... FROM clean.customers)一致,實際撰寫CTE程式碼時各段可互相複製修改,模板一致可減少改動點與漏改的風險)
    SELECT is_churned,
           (total_trans_ct <= 61)              AS f_low,     
           (avg_utilization_ratio = 0)         AS f_zero,
           (total_relationship_count <= 2)     AS f_shallow,
           (contacts_count_12_mon >= 4)        AS f_contact,
           (total_amt_chng_q4_q1 < 0.604)      AS f_decline
    FROM clean.customers
)
SELECT
  -- 計算方式: 條件計數句(SUM((條件)::int) = 計算「符合條件的列數」

  -- 1. 算: 5 個旗標各自有多少客戶符合條件 (5 旗標各自有多少人) (將每個旗標中分別有多少 true 的數量用 SUM 算出來)。
  -- 目的: 得出「計算重疊比例時」的「分母」。eg.「low_x_zero 交集 1,165 人」單獨看沒意義,要看「1,165 佔零動用名單(2,470)的幾成」才有意義,如判讀重點第一項所述)。
  SUM(f_low::int)     AS n_low,      -- 低活躍名單人數 ( = f_low 為 True 的列數)
  SUM(f_zero::int)    AS n_zero,     -- 零動用名單人數
  SUM(f_shallow::int) AS n_shallow,  -- 淺關係名單人數
  SUM(f_contact::int) AS n_contact,  -- 高聯繫名單人數
  SUM(f_decline::int) AS n_decline,  -- 消費下滑名單人數
  -- 2. 算: 4 個正式旗標兩兩交集的人數(共 6 組)分別是多少 (SUM((a AND b)::int) 是「條件計數」,True為1、False為0，加總結果就是 True 的人數)
  SUM((f_low AND f_zero)::int)        AS low_x_zero,        -- 既在低活躍名單、又在零動用名單的人數 ( = f_low 和 f_zero 皆為 True 的列數)
  SUM((f_low AND f_shallow)::int)     AS low_x_shallow,     -- 既在低活躍名單、又在淺關係名單的人數
  SUM((f_low AND f_contact)::int)     AS low_x_contact,     -- 既在低活躍名單、又在高聯繫名單的人數
  SUM((f_zero AND f_shallow)::int)    AS zero_x_shallow,    -- 既在零動用名單、又在淺關係名單的人數
  SUM((f_zero AND f_contact)::int)    AS zero_x_contact,    -- 既在零動用名單、又在高聯繫名單的人數
  SUM((f_shallow AND f_contact)::int) AS shallow_x_contact, -- 既在淺關係名單、又在高聯繫名單的人數
