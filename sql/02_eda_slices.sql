-- ============================================================
-- 以 H1 為例，兩步驟的理解與最終輸出如下 (binned是中間表，代表「已分箱的中間資料表」；quintile是各組的號碼牌，eg. 分五組，quintile 就分別是1、2、3、4、5)：
-- 第一層 (產出中間表)：內部先用窗口函數做完 NTILE(5) OVER (ORDER BY total_trans_ct) 後得出的中間表 binned (10,127 列 × 3 欄：每列是一個客戶的「箱號、交易筆數、是否流失」)：
-- quintile | total_trans_ct | is_churned
--    1     |      10        |   true
--    1     |      12        |   true
--   ...
--    3     |      64        |   false
--   ...
--    5     |     139        |   false

-- 第二層 (針對第一層產出的中間表做最終查詢，得出結果)：外層查詢 (SELECT ... ORDER BY quintile; 這段)後最終輸出的長相 (數字僅示意，非真實資料)：
--  grp |  n   | bin_min | bin_max | churn_pct | diff_pp
--   1  | 2026 |   10    |   41    |   31.44   | +15.37
--   2  | 2026 |   41    |   61    |   37.22   | +21.15
--   3  | 2025 |   61    |   73    |    7.11   |  -8.96
--   4  | 2025 |   73    |   83    |    3.51   | -12.56
--   5  | 2025 |   83    |  139    |    1.04   | −15.03
-- ============================================================


-- ============================================================
-- H1：近 12 個月內的交易筆數 (預期：負相關，交易筆數越低、流失率越高)
-- 依交易筆數的大小做排序、然後依總客戶數等量分箱成五組，觀察每一組的流失率 & 各組間流失率的變化趨勢
WITH binned AS (
    SELECT NTILE(5) OVER (ORDER BY total_trans_ct) AS quintile,
           total_trans_ct, is_churned
    FROM clean.customers
)
SELECT quintile AS grp, COUNT(*) AS n,
       MIN(total_trans_ct) AS bin_min, MAX(total_trans_ct) AS bin_max,
       ROUND(100.0 * AVG(is_churned::int), 2) AS churn_pct,
       ROUND(100.0 * AVG(is_churned::int) - 16.07, 2) AS diff_pp
FROM binned
GROUP BY quintile
ORDER BY quintile;
-- ============================================================




-- ============================================================
-- H3：消費金額變化比 Q4/Q1 (預期：負相關，下滑組流失率高：消費金額變化比越低 (Q4消費金額比Q1消費金額低)，流失率越高；上升組流失率低：消費金額變化比越高 (Q4消費金額比Q1消費金額高)，流失率越低)(若 Q1和Q4的消費金額持平，total_amt_chng_q4_q1 會是 1)。
-- 依消費金額變化比的大小做排序、然後依總客戶數等量分箱成五組，觀察每一組的流失率 & 各組間流失率的變化趨勢

-- total_amt_chng_q4_q1 是 float，ROUND 到小數點後第三位 (比率的慣例)。ROUND()兩參數版 只接受 numeric 作為參數，所以要先轉。

-- ============================================================
-- H3(消費金額變化比)兩層輸出樣貌：
-- 第一層中間表 binned (10,127 列 × 3 欄；依 total_amt_chng_q4_q1 由小到大發配箱號):
-- quintile | total_amt_chng_q4_q1 | is_churned
--    1     |        0.000         |   true
--    1     |        0.420         |   true
--   ...
--    3     |        0.730         |   false
--   ...
--    5     |        3.397         |   false
-- 第二層最終輸出 (5 列；bin_min、bin_max 值為 float，實際輸出帶小數):
--  grp |  n   | bin_min  | bin_max  | churn_pct | diff_pp
--   1  | 2026 |  0.000   |  0.6xx   |   2x.xx   |  +x.xx
--   2  | 2026 |  0.6xx   |  0.7xx   |   1x.xx   |  ...
--   3  | 2025 |  0.7xx   |  0.7xx   |   1x.xx   |  ...
--   4  | 2025 |  0.7xx   |  0.8xx   |   1x.xx   |  ...
--   5  | 2025 |  0.8xx   |  3.40x   |   1x.xx   |  −x.xx
-- (預期：第 1 箱 (Q4 較 Q1 大幅下滑者)流失率最高，單調遞減)     

WITH binned AS (
    SELECT NTILE(5) OVER (ORDER BY total_amt_chng_q4_q1) AS quintile,
           total_amt_chng_q4_q1, is_churned
    FROM clean.customers
)
SELECT quintile AS grp, COUNT(*) AS n,
       ROUND(MIN(total_amt_chng_q4_q1)::numeric, 3) AS bin_min,
       ROUND(MAX(total_amt_chng_q4_q1)::numeric, 3) AS bin_max,
       ROUND(100.0 * AVG(is_churned::int), 2) AS churn_pct,
       ROUND(100.0 * AVG(is_churned::int) - 16.07, 2) AS diff_pp
FROM binned
GROUP BY quintile
ORDER BY quintile;
