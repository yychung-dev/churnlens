-- 1.Kaggle 教學資料集常有加工痕跡,而加工過程有幾種很典型的做法會製造單值聚集預設值,eg.1.生成程式對缺資料的客戶填一個預設 tenure(例如 36);2.合成分布的截斷或取整:若 tenure 是用某個分布隨機生成再取整,分布中心附近的值會被大量重複命中;3.抽樣偏差:上游從某個母體抽樣時,剛好對「在冊約三年」的客群過度抽取。以上都只是有可能發生的情形,但無法判定,因為判定需要上游的生成文件(本案沒有),所以僅列出「真實業務原因(如獲客活動)」與「加工痕跡」兩類候選並標記。
-- 另外,這份資料已有兩個類似問題(nb 模型欄、age×tenure 高相關)可能是上游加工痕跡,所以此處「加工痕跡」的懷疑機率不低,此僅為分析猜測,不是正式判定。

-- 2.一個變數的資訊量,來自它能把不同的人分開:每個人的值都不同,變數就能提供最細的區分;所有人的值都相同,變數就什麼都分不出來(極端例子:全部人都是 36,這欄就等於沒有)。tenure 的情況介於中間:2,463 人(近四分之一)擠在 36 這一個值上。對這群人,tenure 給出的是一模一樣的答案,模型若想在他們之間分辨誰高風險、誰低風險,tenure 幫不上任何忙,只能靠其他變數來分辨。所以表面上 tenure 有 13 到 56 共 44 種值、看起來解析度很高,實際上它對四分之一的樣本都是「同一句話」、都是 36,如此,區分能力的效果其實很低,只是值域看起來區分能力不低而已。
