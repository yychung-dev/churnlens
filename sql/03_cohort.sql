-- sql/03_cohort.sql — M2 階段 D:代理 cohort(H9)
-- 執行:docker exec -i churnlens-pg psql -U postgres -d churnlens < sql/03_cohort.sql

-- 目的:以在冊月數(months_on_book)分箱,檢視客戶生命週期各階段的流失率,驗證 H9。
-- H9: 假設「以 tenure 劃分的客戶生命週期階段」與流失有關聯(不預設關聯方向是正相關或負相關)；

-- 分箱決策:將在冊月數依不同年段分組,依「年度區間」分組 (每 12 個月一組,以下簡稱年段),不用 NTILE (依客戶筆數均分),第四箱僅 8 個月,因資料 max=56。
-- 理由:年段是生命週期敘事的業務語言(客戶與銀行往來的第 2/3/4/5 年),銀行看 tenure 是按年看,供決策者直接判讀(見 [M2-11])。(「NTILE 第三分位」對業務需求的讀者無意義)

-- 邊界依據:分箱範圍依 M1 稽核 [D] 實測 months_on_book min=13、max=56;ELSE 分支僅可能接住 49–56。
--   注意:此寫法依賴「max=56」的稽核事實;若資料更新出現 >56 的值,ELSE 會將其靜默歸入「49-56」標籤,屆時應改為明確的 BETWEEN 邊界作為防禦型寫法。eg. WHEN months_on_book BETWEEN 49 AND 56 + ELSE '超出預期範圍'。
--   本案是已凍結的快照資料,故採現行寫法。

-- 方法定位:本資料為單一時點快照,此為代理 cohort(pseudo-cohort),非真世代追蹤;
-- 以「單一時點快照(橫斷面資料)」這個替代方法,模擬「世代分析 (縱向追蹤)的 客戶生命週期各階段樣貌」;這個方法的先天限制:倖存者偏差

--  三項方法限制: 1.倖存者偏差、2.tenure × age 混淆、3.無新戶。見 notebook 階段 D 判讀。
-- ============================================================
-- [D1] 輸出樣貌: (4 rows)
--    tenure_band   |   n   |  churn_pct |  diff_pp
--    13-24(第2年)  |   847  |   14.88    |  -1.19
--    25-36(第3年)  |  5418  |   16.08    |  +0.01
--    37-48(第4年)  |  3207  |   16.18    |  +0.11
--    49-56(第5年)  |   655  |   16.95    |  +0.88

-- [D1-補] 輸出樣貌: (5 rows)
--      val  |   n
--  ---------+------
--      36   |  2463      
--      37   |  358      
--      34   |  353
--      38   |  347
--      39   |  341
-- ============================================================

-- [D1] 依年段分箱,各年段的流失率
SELECT CASE
         WHEN months_on_book BETWEEN 13 AND 24 THEN '13-24(第2年)'
         WHEN months_on_book BETWEEN 25 AND 36 THEN '25-36(第3年)'
         WHEN months_on_book BETWEEN 37 AND 48 THEN '37-48(第4年)'
         ELSE '49-56(第5年)'
       END AS tenure_band,
       COUNT(*) AS n,
       ROUND(100.0 * AVG(is_churned::int), 2) AS churn_pct,
       ROUND(100.0 * AVG(is_churned::int) - 16.07, 2) AS diff_pp
FROM clean.customers
GROUP BY 1
ORDER BY MIN(months_on_book);


-- ==========================================================
-- 語法筆記:
-- (1) GROUP BY 1 = 按 SELECT 的第 1 個輸出欄(CASE 算出的 tenure_band)分組,就不需要重抄整段 CASE。
-- (2) ORDER BY MIN(months_on_book) = 依「各組內最小在冊月數」排序 (eg.「13-24」那組的 MIN 是 13、「25-36」是 25);因各箱標籤(eg. '13-24(第2年)')是文字,預設依字典序排,無法依時間由小到大的邏輯排序,所以改以「組內最小值」排序即能得出「時間順序」。
-- (3) ORDER BY 可使用 MIN(months_on_book) 這個聚合函數來排序,因為排序行為是發生在分組行為之後,要排序時已經分好組了,所以可以拿該組的 MIN 來排序 : 
-- SQL 的邏輯執行順序是: FROM → WHERE → GROUP BY(此時計算 CASE 決定每列所屬組)→ 聚合 → SELECT → ORDER BY。排序發生在最後,分組與聚合皆已完成,故可用MIN()這個聚合函數來拿各組的 MIN 來排序。
-- 本查詢的實際流程:FROM 取出 clean.customers 全部 10,127 列 →(無 WHERE,不過濾)→ GROUP BY:對每列計算 CASE 得出所屬 tenure_band,分成四組 → 聚合:每組算 COUNT、AVG、MIN → SELECT:組出四列輸出 → ORDER BY:按各組的 MIN 排序。
-- GROUP BY 1 的「1」為位置參照,指向 SELECT 清單第 1 個運算式,該運算式實際於分組時計算。
-- ==========================================================

-- ==========================================================
-- [D1-補] 單值出現頻率的檢查:列出「在冊月數」人數最多的前 5 個單值
-- 目的:四箱人數懸殊(847 / 5,418 / 3,207 / 655),此查詢對整個欄位檢查是否存在單值集中,回答「人數多的箱,是各月份平均累積,還是個別月數異常集中」。
-- 實測:僅 36 一值出現集中(2,463 人,佔 25–36 箱的 45%);其餘前幾大單值皆三百餘人,37–48 箱即由此類月份累積而成,無單值集中。

-- 含義:判讀 25–36 箱流失率時,須知其近半權重來自 tenure=36 的客戶。此聚集之成因無法由本資料判定,可能為上游生成方式、或快照前約 36 個月的大型獲客活動等,不影響 H9 的判定,列為資料特徵記錄。
-- 此含義在後續工作階段的可能情形: (1)階段 E / M8 畫圖時:任何以 tenure 為軸的圖,36 的位置都會出現一根突兀的高柱。有這筆記錄,圖的註解可以直接寫「36 個月處的集中為已知資料特徵」,不用重新查原因;若無記錄可能會讓讀圖的人第一時間以為「圖是否畫錯」。(2)M4 建模時:若 tenure 進模型(依 [M1-5] 是二擇一的候選之一),近四分之一樣本擠在同一個值,會讓這個變數的資訊量比表面上低,屆時特徵取捨時要參考這筆記錄。

-- 補充: 資料裡任何「解釋不了的形狀」都要留下紀錄,防止之後或其他人看到時當成錯誤,或重新花時間查一次。

SELECT months_on_book AS val, COUNT(*) AS n
FROM clean.customers
GROUP BY months_on_book
ORDER BY n DESC
LIMIT 5;




